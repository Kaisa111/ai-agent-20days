
import math
import re

from day17.schemas import ResearchEvidence


def extract_claim_tvl(claim: str) -> float | None:
    """
    Extract a USD TVL value from the standardized
    claim format generated by market_evidence.py.
    """

    pattern = (
        r"has a reported TVL of "
        r"\$([\d,]+(?:\.\d+)?) USD\."
    )

    match = re.search(pattern, claim)

    if not match:
        return None

    return float(
        match.group(1).replace(",", "")
    )


def validate_numeric_evidence(
    evidence: ResearchEvidence,
    protocol: dict,
) -> ResearchEvidence:
    """
    Compare the claim against structured API data.

    Verified means consistent with the supplied
    API snapshot, not independently true.
    """

    evidence.verification_status = "unverified"

    if evidence.source_type != "api":
        return evidence

    name = protocol.get("name")
    tvl = protocol.get("tvl")

    if not isinstance(name, str) or not name:
        return evidence

    if (
        isinstance(tvl, bool)
        or not isinstance(tvl, (int, float))
        or not math.isfinite(tvl)
        or tvl < 0
    ):
        return evidence

    # Only accept the standardized claim format
    pattern = (
        rf"^{re.escape(name)} has a reported TVL "
        rf"of \$[\d,]+(?:\.\d+)? USD\.$"
    )

    if not re.fullmatch(pattern, evidence.claim):
        return evidence

    claim_tvl = extract_claim_tvl(
        evidence.claim
    )

    if claim_tvl is None:
        return evidence

    # Market claims display two decimal places
    expected_tvl = round(float(tvl), 2)

    if math.isclose(
        claim_tvl,
        expected_tvl,
        rel_tol=0,
        abs_tol=0.005,
    ):
        evidence.verification_status = "verified"
    else:
        evidence.verification_status = "contradicted"

    return evidence
